# executes the precompile statements like PackageCompiler (`create_sysimg_object_file`) does,
# loaded modules are available by name (the FMU module and FMICore)
function runPrecompileStatements(files, modules)
    staging = Module()
    for (name, mod) in modules
        Core.eval(staging, :(const $(name) = $(mod)))
    end

    results = Dict{String,Bool}()
    for file in files, statement in eachline(file)
        ps = Meta.parse(statement) # throws for invalid syntax (PackageCompiler skips the statement)
        Meta.isexpr(ps, :call) || continue
        popfirst!(ps.args) # precompile(...)
        ps.head = :tuple
        results[statement] = precompile(Core.eval(staging, ps)...)
    end
    return results
end

# generates the FMU module from the FMU source template and checks its precompile statements
function testPrecompileStatements(fmu, fmu_name; debug = false)
    templates = FMIBuild.assembleBuildTemplates(mktempdir(), fmu_name, fmu; debug = debug)

    # the FMU module as generated by `saveFMU`, the C entry points are not needed to precompile
    code = replace(
        read(templates.fmu_source_template, String),
        "Base.@ccallable function" => "function",
    )
    fmu_module = Core.eval(
        Main,
        Expr(:module, true, Symbol(fmu_name), Expr(:block, Meta.parseall(code).args...)),
    )

    results = runPrecompileStatements(
        templates.precompile_statements_file,
        (Symbol(fmu_name) => fmu_module, :FMICore => FMICore),
    )
    @test length(results) > 0
    @test all(values(results))

    # every entry point of the FMU is precompiled
    entry_points = Set(
        m.captures[1] for m in eachmatch(
            r"Base\.@ccallable function (jl_\w+)",
            read(templates.fmu_source_template, String),
        )
    )
    precompiled = Set(
        m.captures[1] for statement in keys(results) for
        m in eachmatch(Regex(fmu_name * raw"\.(jl_\w+)"), statement)
    )
    @test precompiled == entry_points

    # the FMU module extends the FMIBase log functions for instance pointers, these methods are removed,
    # so the next FMU module does not overwrite them (a real FMU holds only one FMU module)
    for f in (FMIBase.logInfo, FMIBase.logWarning, FMIBase.logError), m in methods(f)
        m.module == fmu_module && Base.delete_method(m)
    end
end

# build modes of the FMU source template (keyword `debug` of `saveFMU`)
const BUILD_MODES = ("release" => false, "debug" => true)

@testset "FMIBuild" verbose = true begin
    @testset "FMI2" verbose = true begin
        @testset "Templates" begin
            fmu = createTestFMU2(; me = false)
            templates = FMIBuild.assembleBuildTemplates(mktempdir(), "Test", fmu)
            @test templates.interfaces == [:CS]
            @test endswith(
                templates.fmu_source_template,
                joinpath("FMI2", "julia", "FMU_content.jl"),
            )

            c_code = read(templates.julia_init_c_file, String)
            @test occursin("fmi2Instantiate", c_code)
            @test occursin("fmi2DoStep", c_code)
            @test !occursin("fmi2GetDerivatives", c_code)

            platform, libext = FMIBuild.binaryPlatform(fmu)
            @test !isnothing(platform)
            @test !isnothing(libext)

            fmu.modelDescription.coSimulation = nothing
            @test_throws AssertionError FMIBuild.templateInterfaces(fmu)
        end

        @testset "Model description" begin
            md = createTestFMU2().modelDescription
            md.numberOfEventIndicators = UInt(0)
            md.coSimulation.canInterpolateInputs = true

            x = fmi2ScalarVariable(
                "x",
                fmi2ValueReference(1),
                fmi2CausalityOutput,
                fmi2VariabilityContinuous,
                fmi2InitialExact,
            )
            x.Real = FMICore.fmi2RealAttributesExt()
            x.Real.start = 1.0
            dx = fmi2ScalarVariable(
                "der(x)",
                fmi2ValueReference(2),
                fmi2CausalityLocal,
                fmi2VariabilityContinuous,
                nothing,
            )
            dx.Real = FMICore.fmi2RealAttributesExt()
            dx.Real.derivative = UInt(1)
            flag = fmi2ScalarVariable(
                "flag",
                fmi2ValueReference(3),
                fmi2CausalityParameter,
                fmi2VariabilityFixed,
                fmi2InitialExact,
            )
            flag.Boolean = FMICore.fmi2BooleanAttributesExt()
            flag.Boolean.start = fmi2True
            u = fmi2ScalarVariable(
                "u",
                fmi2ValueReference(4),
                fmi2CausalityInput,
                fmi2VariabilityContinuous,
                nothing,
            )
            u.canHandleMultipleSetPerTimeInstant = fmi2False
            u.Real = FMICore.fmi2RealAttributesExt()
            u.Real.start = 0.0
            md.modelVariables = [x, dx, flag, u]

            out = fmi2VariableDependency(UInt(1))
            out.dependencies = UInt[] # depends on no known
            out.dependenciesKind = fmi2DependencyKind[]
            der = fmi2VariableDependency(UInt(2))
            der.dependencies = UInt[1]
            der.dependenciesKind = [fmi2DependencyKindDependent]
            md.modelStructure.outputs = [out]
            md.modelStructure.derivatives = [der]

            path = joinpath(mktempdir(), "modelDescription.xml")
            FMIBuild.saveModelDescription(md, path)
            root = readxml(path).root

            @test root["fmiVersion"] == "2.0"
            @test root["guid"] == md.guid
            @test root["numberOfEventIndicators"] == "0"

            nodes = Dict(node.name => node for node in eachelement(root))
            @test haskey(nodes, "ModelExchange")
            @test nodes["CoSimulation"]["canInterpolateInputs"] == "true"

            variables = collect(eachelement(nodes["ModelVariables"]))
            @test all(v.name == "ScalarVariable" for v in variables)
            @test [v["name"] for v in variables] == ["x", "der(x)", "flag", "u"]
            @test variables[4]["canHandleMultipleSetPerTimeInstant"] == "false"
            types = [first(eachelement(v)) for v in variables]
            @test [t.name for t in types] == ["Real", "Real", "Boolean", "Real"]
            @test types[1]["start"] == "1.0"
            @test types[2]["derivative"] == "1"
            @test types[3]["start"] == "true"

            structure =
                Dict(node.name => node for node in eachelement(nodes["ModelStructure"]))
            @test sort(collect(keys(structure))) == ["Derivatives", "Outputs"]
            unknown = first(eachelement(structure["Outputs"]))
            @test unknown["index"] == "1"
            @test unknown["dependencies"] == "" # omitting means "depends on all knowns"
            @test unknown["dependenciesKind"] == ""
            unknown = first(eachelement(structure["Derivatives"]))
            @test unknown["index"] == "2"
            @test unknown["dependencies"] == "1"
            @test unknown["dependenciesKind"] == "dependent"
        end

        @testset "Precompile statements ($(mode))" for (mode, debug) in BUILD_MODES
            testPrecompileStatements(
                createTestFMU2(),
                "PrecompileTestFMI2" * titlecase(mode);
                debug = debug,
            )
        end
    end

    @testset "FMI3" verbose = true begin
        @testset "Templates" begin
            fmu = createTestFMU3(; cs = false)
            templates = FMIBuild.assembleBuildTemplates(mktempdir(), "Test", fmu)
            @test templates.interfaces == [:ME]
            @test endswith(
                templates.fmu_source_template,
                joinpath("FMI3", "julia", "FMU_content.jl"),
            )

            c_code = read(templates.julia_init_c_file, String)
            @test occursin("fmi3InstantiateModelExchange", c_code)
            @test occursin("fmi3GetContinuousStateDerivatives", c_code)
            @test !occursin("fmi3DoStep", c_code)

            platform, libext = FMIBuild.binaryPlatform(fmu)
            @test !isnothing(platform)
            @test !isnothing(libext)

            fmu.modelDescription.scheduledExecution =
                FMICore.fmi3ModelDescriptionScheduledExecution("Test")
            @test_throws AssertionError FMIBuild.templateInterfaces(fmu)
        end

        @testset "Model description" begin
            md = createTestFMU3().modelDescription
            md.coSimulation.canInterpolateInputs = true # FMI 2 only, not written

            x = FMICore.fmi3VariableFloat64("x", fmi3ValueReference(1))
            x.causality = fmi3CausalityOutput
            x.initial = fmi3InitialExact
            x.start = 1.0
            dx = FMICore.fmi3VariableFloat64("der(x)", fmi3ValueReference(2))
            dx.derivative = fmi3ValueReference(1)
            flag = FMICore.fmi3VariableBoolean("flag", fmi3ValueReference(3))
            flag.causality = fmi3CausalityParameter
            flag.variability = fmi3VariabilityFixed
            flag.initial = fmi3InitialExact
            flag.start = fmi3True
            md.modelVariables = [x, dx, flag]

            out = fmi3VariableDependency(UInt(1))
            out.dependencies = UInt[] # depends on no known
            out.dependenciesKind = fmi3DependencyKind[]
            der = fmi3VariableDependency(UInt(2))
            der.dependencies = UInt[1]
            der.dependenciesKind = [fmi3DependencyKindDependent]
            md.modelStructure.outputs = [out]
            md.modelStructure.continuousStateDerivatives = [der]

            path = joinpath(mktempdir(), "modelDescription.xml")
            FMIBuild.saveModelDescription(md, path)
            root = readxml(path).root

            @test root["fmiVersion"] == "3.0"
            @test root["instantiationToken"] == md.instantiationToken
            @test !haskey(root, "numberOfEventIndicators")

            nodes = Dict(node.name => node for node in eachelement(root))
            @test haskey(nodes, "ModelExchange")
            @test !haskey(nodes["CoSimulation"], "canInterpolateInputs")

            variables = collect(eachelement(nodes["ModelVariables"]))
            @test [v.name for v in variables] == ["Float64", "Float64", "Boolean"]
            @test variables[2]["derivative"] == "1"
            @test variables[3]["start"] == "true"

            unknowns = collect(eachelement(nodes["ModelStructure"]))
            @test [u.name for u in unknowns] == ["Output", "ContinuousStateDerivative"]
            @test unknowns[1]["dependencies"] == "" # omitting means "depends on all knowns"
            @test unknowns[1]["dependenciesKind"] == ""
            @test unknowns[2]["valueReference"] == "2"
            @test unknowns[2]["dependencies"] == "1"
            @test unknowns[2]["dependenciesKind"] == "dependent"
        end

        @testset "Precompile statements ($(mode))" for (mode, debug) in BUILD_MODES
            testPrecompileStatements(
                createTestFMU3(),
                "PrecompileTestFMI3" * titlecase(mode);
                debug = debug,
            )
        end
    end
end
